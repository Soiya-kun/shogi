import {writeFile} from 'node:fs/promises';
import {initial,legal,apply} from '../dist/rules.mjs';
import {fromUSI,toUSI,toSFEN} from '../dist/ai/usi-codec.mjs';
// Original short setup branches, not a third-party professional game database.
const plans={
  static:[['7g7f','2g2f','2f2e','7i6h','6i7h','5i6i','6i7i'],['2g2f','7g7f','2f2e','7i6h','6i7h','5i6i','6i7i']],
  fourth:[['7g7f','6g6f','2h6h','5i4h','4h3h','3h2h','3i3h'],['6g6f','7g7f','2h6h','5i4h','4h3h','3h2h','3i3h']],
  central:[['5g5f','2h5h','5f5e','5i4h','4h3h','3h2h','3i3h'],['7g7f','5g5f','2h5h','5i4h','4h3h','3h2h','3i3h']],
};
const book={};
for(const [a,aa] of Object.entries(plans))for(const ap of aa)for(const [b,bb] of Object.entries(plans))for(const bp of bb){
  let g=initial();const step=[0,0];
  for(let ply=0;ply<14;ply++){
    const side=g.turn,text=(side?bp:ap)[step[side]++];let m=fromUSI(text);
    if(side)m={...m,from:80-m.from,to:80-m.to};
    if(!legal(g).some(v=>toUSI(v)===toUSI(m)))break;
    const normalized=side?{...g,b:[...g.b].reverse().map(p=>p?{...p,s:1-p.s}:null),h:[g.h[1],g.h[0]],turn:0}:g;
    const k=toSFEN(normalized).split(' ').slice(0,3).join(' '),style=side?b:a;
    book[k]??={};book[k][style]??=[];if(!book[k][style].includes(text))book[k][style].push(text);
    g=apply(g,m);
  }
}
await writeFile(new URL('../dist/ai/openings/book.mjs',import.meta.url),'// Generated by scripts/build-openings.mjs. Original legal setup branches.\nexport const BOOK='+JSON.stringify(book,null,2)+';\n');
console.log(`Generated ${Object.keys(book).length} opening positions`);
